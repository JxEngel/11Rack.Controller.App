class SevenBitCodecTests : public juce::UnitTest
{
public:
    SevenBitCodecTests() : juce::UnitTest ("SevenBitCodec", "Rack") {}

    void runTest() override
    {
        beginTest ("encodeValue(127) matches the real hardware-verified Main Volume encoding");
        {
            auto encoded = SevenBitCodec::encodeValue (127);
            std::vector<uint8_t> expected { 0x3F, 0x7F, 0x7F, 0x7F, 0x0F };
            expect (encoded == expected);
        }

        beginTest ("decodeValue on the real captured Main Volume reply decodes to 127");
        {
            // Reply was F0 13 0B 0F 12 36 00 3F 7F 7F 7F 0F F7 - the value bytes (after command
            // and the "00" sub-param) are 3F 7F 7F 7F 0F.
            std::vector<uint8_t> encoded { 0x3F, 0x7F, 0x7F, 0x7F, 0x0F };
            expectEquals ((int) SevenBitCodec::decodeValue (encoded), 127);
        }

        beginTest ("encodeValue then decodeValue round-trips for a non-special-case value");
        {
            // 64 doesn't hit the 126/127 special case, so this exercises the general linear path.
            auto encoded = SevenBitCodec::encodeValue (64);
            expectEquals ((int) SevenBitCodec::decodeValue (encoded), 64);
        }

        beginTest ("encodeTo7Bits output only ever contains 7-bit-safe bytes");
        {
            std::vector<uint8_t> input { 0x00, 0xFF, 0x80, 0x7F, 0x01 };
            auto encoded = SevenBitCodec::encodeTo7Bits (input);
            for (auto b : encoded)
                expect (b <= 0x7F);
        }

        beginTest ("decodeFrom7Bits(encodeTo7Bits(x)) reproduces x when the known trailing "
                   "remainder byte is dropped (see SevenBitCodec.h for why that byte exists)");
        {
            const std::vector<std::vector<uint8_t>> cases = {
                { 0x00 },
                { 0x7F },
                { 0x00, 0xFF },
                { 0x01, 0x02, 0x03, 0x04, 0x05 },
            };

            for (const auto& original : cases)
            {
                auto encoded = SevenBitCodec::encodeTo7Bits (original);
                auto decoded = SevenBitCodec::decodeFrom7Bits (encoded);

                expect (decoded.size() == original.size() + 1);
                std::vector<uint8_t> truncated (decoded.begin(), decoded.begin() + (long) original.size());
                expect (truncated == original);
            }
        }

        beginTest ("full round-trip against the real captured bulk-rig payload: decode, drop the "
                   "trailing remainder byte, re-encode, and get back the EXACT original wire bytes "
                   "captured from real hardware");
        {
            auto decoded = SevenBitCodec::decodeFrom7Bits (kRealBulkRigParams);
            expect (! decoded.empty());

            std::vector<uint8_t> withoutRemainder (decoded.begin(), decoded.end() - 1);
            auto reEncoded = SevenBitCodec::encodeTo7Bits (withoutRemainder);

            expect (reEncoded == kRealBulkRigParams);
        }
    }
};

